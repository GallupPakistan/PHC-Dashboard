def get_date_form_pdf_links(form_url, session, lookback_days=3):
    links = []
    end_date = date.today()
    start_date = end_date - timedelta(days=lookback_days)
    d = start_date
    while d <= end_date:
        date_str = d.isoformat()
        try:
            resp = session.post(form_url, data={"dated": date_str}, headers=HEADERS, timeout=30)
            resp.raise_for_status()
            soup = BeautifulSoup(resp.text, "html.parser")
            for a in soup.find_all("a", class_="btn-success", href=True):
                links.append(a["href"])
        except Exception as e:
            print(f"    [debug] {form_url} dated={date_str}: fetch failed ({e})")
        d += timedelta(days=1)
    return links


def get_json_api_pdf_links(api_url, session, max_pages=5):
    links = []
    page = 1
    while page <= max_pages:
        resp = session.get(api_url, params={"page": page, "limit": 10}, headers=HEADERS, timeout=30)
        resp.raise_for_status()
        payload = resp.json()
        data = payload.get("data", [])
        if not data:
            break
        for item in data:
            path = item.get("path")
            if path:
                links.append(path)
        total = payload.get("total", 0)
        if page * payload.get("limit", 10) >= total:
            break
        page += 1
    return links


