def parse_mingora_html(html_text, source_url, bench_name, global_sr_holder):
    soup = BeautifulSoup(html_text, "html.parser")
    records = []

    # judge name — the grid div right after the label "Before"
    judge = ""
    for div in soup.find_all("div", style=True):
        if "grid-template-columns" in div.get("style", ""):
            cells = div.find_all("div")
            if len(cells) >= 2 and "Before" in cells[0].get_text(strip=True):
                judge = cells[1].get_text(strip=True)
            break

    # date/title
    h3 = soup.find("h3")
    title_text = h3.get_text(" ", strip=True) if h3 else ""

    current_section = ""
    for tr in soup.find_all("tr"):
        section_div = tr.find("div", style=lambda s: s and "text-decoration: underline" in s)
        if section_div:
            current_section = section_div.get_text(strip=True)
            continue

        tds = tr.find_all("td", recursive=False)
        if len(tds) < 4:
            continue

        sr_no = tds[0].get_text(strip=True)
        if not sr_no or not sr_no[0].isdigit():
            continue

        case_cell = tds[1]
        case_no_tag = case_cell.find("strong", class_="case-number")
        case_no = case_no_tag.get_text(strip=True) if case_no_tag else case_cell.get_text(" ", strip=True)

        petitioner_cell = tds[2] if len(tds) > 2 else None
        pet_tag = petitioner_cell.find("strong", class_="case-number") if petitioner_cell else None
        petitioner = pet_tag.get_text(strip=True) if pet_tag else ""
        pet_advocate = ""
        if petitioner_cell:
            adv_divs = petitioner_cell.find_all("div")
            pet_advocate = " ".join(d.get_text(strip=True) for d in adv_divs if d.get_text(strip=True))

        respondent_cell = tds[4] if len(tds) > 4 else None
        res_tag = respondent_cell.find("strong", class_="case-number") if respondent_cell else None
        respondent = res_tag.get_text(strip=True) if res_tag else ""
        res_advocate = ""
        if respondent_cell:
            spans = respondent_cell.find_all("span")
            res_advocate = " ".join(s.get_text(strip=True) for s in spans if s.get_text(strip=True))

        case_title = f"{petitioner} Vs {respondent}" if petitioner and respondent else (petitioner or respondent)
        case_cat = "Notice Case" if "NOTICE" in current_section.upper() else "Motion Case"

        global_sr_holder[0] += 1
        records.append({
            "Source_File": source_url, "Page": 1, "Bench": bench_name,
            "Day": "", "Date": "", "Month": "", "Year": "",
            "Court_No": "", "Judges": judge,
            "Case_Category": case_cat, "Section": current_section,
            "Sr_No": sr_no, "Case_No": case_no, "System_ID": "",
            "Case_Title": case_title, "Petitioner_Advocate": pet_advocate,
            "Respondent_Advocates": res_advocate,
            "Needs_Review": "No" if (petitioner and respondent and case_no) else "Yes",
        })

    return records


def get_case_registry_records(search_url, session, caseyear, casenamecode, global_sr_holder):
    payload = {
        "casetitle": "",
        "caseno": "",
        "caseyear": caseyear,
        "casenamecode": casenamecode,
    }
    resp = session.post(search_url, data=payload, headers=HEADERS, timeout=30)
    resp.raise_for_status()
    result = resp.json()
    rows = result.get("data", [])

    records = []
    for row in rows:
        global_sr_holder[0] += 1
        petitioner = (row.get("PARTY") or "").strip()
        respondent = (row.get("PARTY1") or "").strip()
        case_title = f"{petitioner} Vs {respondent}" if petitioner and respondent else (petitioner or respondent)
        case_type_label = (row.get("CASECODEDTL") or "").split("@")[-1] if row.get("CASECODEDTL") else ""
        case_no = f"{case_type_label} {row.get('CASENO', '')}/{row.get('CASEYEAR', '')}".strip()
        disposed = bool(row.get("DISPOSALDATE"))

        records.append({
            "Source_File": search_url, "Page": 1, "Bench": "D.I.Khan",
            "Day": "", "Date": row.get("INSTITUTIONDATE", "") or "",
            "Month": "", "Year": row.get("CASEYEAR", "") or "",
            "Court_No": row.get("BENCH", "") or "", "Judges": "",
            "Case_Category": "Disposed" if disposed else "Pending", "Section": row.get("COMMENTS", "") or "",
            "Sr_No": str(global_sr_holder[0]), "Case_No": case_no, "System_ID": row.get("CASECODE", "") or "",
            "Case_Title": case_title, "Petitioner_Advocate": "", "Respondent_Advocates": "",
            "Needs_Review": "No" if (petitioner and respondent) else "Yes",
        })
    return records


